#include <stdio.h>

// Simple calculator performing addition, subtraction, multiplication, division
int main() {
    int a = 10, b = 5;

    // Addition
    printf("Sum: %d\n", a + b);

    // Subtraction
    printf("Difference: %d\n", a - b);

    // Multiplication
    printf("Product: %d\n", a * b);

    // Division
    printf("Quotient: %d\n", a / b);

    return 0;
}